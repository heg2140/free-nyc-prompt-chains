import Link from "next/link";
import { notFound } from "next/navigation";
import { deleteRun } from "@/app/chains/actions";
import { DeleteButton } from "@/components/delete-button";
import { describeInputs, StatusBadge, type RunStatus } from "@/components/run-summary";
import { SuggestionCard } from "@/components/suggestion-card";
import { requireSuperadmin } from "@/lib/auth";
import { parseId, type RunInputs, type Suggestion } from "@/lib/chain";
import { card, errorBox, formatDate, h1, h2, muted, page } from "@/lib/ui";

type RunStep = {
  id: number;
  step_order: number;
  title: string;
  model: string;
  temperature: number | null;
  system_prompt: string | null;
  user_prompt: string;
  output: string | null;
  duration_ms: number | null;
};

export default async function RunPage({ params }: PageProps<"/chains/[id]/runs/[runId]">) {
  const { id, runId: rawRunId } = await params;
  const chainId = parseId(id);
  const runId = parseId(rawRunId);
  if (!chainId || !runId) notFound();

  const { supabase } = await requireSuperadmin();
  const [{ data: run }, { data: steps }] = await Promise.all([
    supabase
      .from("prompt_chain_runs")
      .select("id, inputs, status, error, suggestions, created_at, prompt_chains(name)")
      .eq("id", runId)
      .eq("chain_id", chainId)
      .maybeSingle(),
    supabase
      .from("prompt_chain_run_steps")
      .select("*")
      .eq("run_id", runId)
      .order("step_order")
      .returns<RunStep[]>(),
  ]);
  if (!run) notFound();
  const chainName = (run.prompt_chains as unknown as { name: string } | null)?.name ?? "Chain";
  const suggestions = run.suggestions as Suggestion[] | null;

  return (
    <div className={`${page} max-w-4xl`}>
      <Link href={`/chains/${chainId}/runs`} className={`${muted} hover:underline`}>
        ← Everything generated by {chainName}
      </Link>
      <div className="mt-2 flex flex-wrap items-center justify-between gap-3">
        <h1 className={h1}>Run #{run.id}</h1>
        <DeleteButton action={deleteRun.bind(null, chainId, runId)} label={`run #${run.id}`} />
      </div>
      <div className="mt-2 flex flex-wrap items-center gap-2">
        <StatusBadge status={run.status as RunStatus} />
        <span className={muted}>{formatDate(run.created_at)}</span>
      </div>
      <p className="mt-2 text-sm text-zinc-700 dark:text-zinc-300">{describeInputs(run.inputs as RunInputs)}</p>
      {run.error && <p className={`mt-4 ${errorBox}`}>{run.error}</p>}

      {suggestions?.length ? (
        <section className="mt-6">
          <h2 className={`${h2} mb-3`}>Suggestions</h2>
          <div className="grid gap-3 sm:grid-cols-2">
            {suggestions.map((s, i) => <SuggestionCard key={i} suggestion={s} />)}
          </div>
        </section>
      ) : null}

      <section className="mt-8">
        <h2 className={`${h2} mb-3`}>Step by step</h2>
        <ol className="flex flex-col gap-4">
          {steps?.map((step) => (
            <li key={step.id} className={card}>
              <div className="flex flex-wrap items-baseline justify-between gap-2">
                <h3 className="font-semibold text-zinc-900 dark:text-zinc-50">
                  {step.step_order}. {step.title}
                </h3>
                <span className={muted}>
                  {step.model}
                  {step.temperature !== null && ` · temp ${step.temperature}`}
                  {step.duration_ms !== null && ` · ${(step.duration_ms / 1000).toFixed(1)}s`}
                </span>
              </div>
              <details className="mt-3">
                <summary className={`${muted} cursor-pointer`}>Prompt sent</summary>
                {step.system_prompt && (
                  <pre className="mt-2 whitespace-pre-wrap rounded-lg bg-zinc-100 p-3 font-mono text-xs text-zinc-700 dark:bg-zinc-950 dark:text-zinc-300">
                    <span className="font-semibold">System: </span>{step.system_prompt}
                  </pre>
                )}
                <pre className="mt-2 whitespace-pre-wrap rounded-lg bg-zinc-100 p-3 font-mono text-xs text-zinc-700 dark:bg-zinc-950 dark:text-zinc-300">
                  {step.user_prompt}
                </pre>
              </details>
              <p className={`${muted} mt-3 mb-1`}>Output</p>
              {step.output === null ? (
                <p className="text-sm text-red-700 dark:text-red-300">No output (this step failed).</p>
              ) : (
                <pre className="max-h-96 overflow-auto whitespace-pre-wrap rounded-lg border border-black/[.08] p-3 text-sm text-zinc-800 dark:border-white/[.1] dark:text-zinc-200">
                  {step.output}
                </pre>
              )}
            </li>
          ))}
        </ol>
      </section>
    </div>
  );
}
