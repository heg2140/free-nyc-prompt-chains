import Link from "next/link";
import { notFound } from "next/navigation";
import { describeInputs, StatusBadge, type RunStatus } from "@/components/run-summary";
import { SuggestionCard } from "@/components/suggestion-card";
import { requireSuperadmin } from "@/lib/auth";
import { parseId, type RunInputs, type Suggestion } from "@/lib/chain";
import { card, formatDate, h1, muted, page, secondaryButton } from "@/lib/ui";

const PAGE_SIZE = 10;

type RunRow = {
  id: number;
  inputs: RunInputs;
  status: RunStatus;
  error: string | null;
  final_output: string | null;
  suggestions: Suggestion[] | null;
  created_at: string;
};

export default async function RunsPage({ params, searchParams }: PageProps<"/chains/[id]/runs">) {
  const chainId = parseId((await params).id);
  if (!chainId) notFound();
  const pageNumber = parseId((await searchParams).page) ?? 1;

  const { supabase } = await requireSuperadmin();
  const from = (pageNumber - 1) * PAGE_SIZE;
  const [{ data: chain }, { data: runs, count }] = await Promise.all([
    supabase.from("prompt_chains").select("name").eq("id", chainId).maybeSingle(),
    supabase
      .from("prompt_chain_runs")
      .select("id, inputs, status, error, final_output, suggestions, created_at", { count: "exact" })
      .eq("chain_id", chainId)
      .order("created_at", { ascending: false })
      .range(from, from + PAGE_SIZE - 1)
      .returns<RunRow[]>(),
  ]);
  if (!chain) notFound();
  const pages = Math.max(1, Math.ceil((count ?? 0) / PAGE_SIZE));

  return (
    <div className={page}>
      <Link href={`/chains/${chainId}`} className={`${muted} hover:underline`}>← {chain.name}</Link>
      <h1 className={`${h1} mt-2`}>Generated by {chain.name}</h1>
      <p className={`${muted} mt-1`}>
        {count ?? 0} {count === 1 ? "run" : "runs"}, newest first. Runs are kept here and never appear in the public Explore feed.
      </p>

      <div className="mt-6 flex flex-col gap-5">
        {runs?.length === 0 && (
          <div className={`${card} ${muted} text-center`}>
            Nothing generated yet. Run the chain from its page to see suggestions here.
          </div>
        )}
        {runs?.map((run) => (
          <section key={run.id} className={card}>
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <StatusBadge status={run.status} />
                <span className={muted}>{formatDate(run.created_at)}</span>
              </div>
              <Link href={`/chains/${chainId}/runs/${run.id}`} className={secondaryButton}>
                Step-by-step output
              </Link>
            </div>
            <p className="mt-2 text-sm text-zinc-700 dark:text-zinc-300">{describeInputs(run.inputs)}</p>

            {run.suggestions?.length ? (
              <div className="mt-4 grid gap-3 sm:grid-cols-2">
                {run.suggestions.map((s, i) => <SuggestionCard key={i} suggestion={s} />)}
              </div>
            ) : run.status === "failed" ? (
              <p className="mt-3 text-sm text-red-700 dark:text-red-300">{run.error}</p>
            ) : run.final_output ? (
              <p className="mt-3 line-clamp-6 whitespace-pre-wrap text-sm text-zinc-700 dark:text-zinc-300">
                {run.final_output}
              </p>
            ) : null}
          </section>
        ))}
      </div>

      {pages > 1 && (
        <nav className="mt-6 flex items-center justify-center gap-3">
          {pageNumber > 1 && (
            <Link href={`?page=${pageNumber - 1}`} className={secondaryButton}>Newer</Link>
          )}
          <span className={muted}>Page {pageNumber} of {pages}</span>
          {pageNumber < pages && (
            <Link href={`?page=${pageNumber + 1}`} className={secondaryButton}>Older</Link>
          )}
        </nav>
      )}
    </div>
  );
}
